/**
 * Represents the state of the keyboard inputs.
 * This class stores boolean values for specific keys to track whether they are currently pressed.
 */
class Keyboard {
    /** @type {boolean} - Indicates if the Left Arrow key is pressed. */
    LEFT = false;

    /** @type {boolean} - Indicates if the Right Arrow key is pressed. */
    RIGHT = false;

    /** @type {boolean} - Indicates if the Up Arrow key is pressed. */
    UP = false;

    /** @type {boolean} - Indicates if the Down Arrow key is pressed. */
    DOWN = false;

    /** @type {boolean} - Indicates if the Spacebar (Jump) is pressed. */
    SPACE = false;

    /** @type {boolean} - Indicates if the 'D' key (Throw/Action) is pressed. */
    D = false;
}